    private static func lines(_ u: URL) -> [String] {
        guard let s = try? String(contentsOf: u, encoding: .utf8) else { return [] }
        return s.split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty && !$0.hasPrefix("#") }
    }

    private static func fillers() -> NSRegularExpression {
        let u = supportDir.appendingPathComponent("fillers.txt")
        let t = FileStamp.capture(u)
        if let r = state.fillerRegex, t == state.fillerStamp { return r }
        let words = fillerDefaults + (t.exists ? lines(u) : [])
        let alts = words.map(NSRegularExpression.escapedPattern(for:)).joined(separator: "|")
        // Sentence-initial fillers ("Um.", "First. Um. Second.") may absorb their own `.?!`
        // tail; mid-utterance fillers ("Let's ship it um. Tomorrow works") absorb only an
        // optional comma and horizontal spaces so sentence-ending `.?!` and `\n` survive.
        let sentenceInitial = "(?:^[ \\t]*|(?<=[\\r\\n])[ \\t]*|(?<=[.!?][ \\t])[ \\t]*)\\b(?:\(alts))\\b(?![-'\\w])[,.!?]?[ \\t]*"
        let midSentence = "\\b(?:\(alts))\\b(?![-'\\w]),?[ \\t]*"
        let r = try! NSRegularExpression(pattern: "(?i)(?:\(sentenceInitial)|\(midSentence))")
        state.fillerRegex = r
        state.fillerStamp = t
        log("fillers loaded: \(words.count) words")
        return r
    }

    /// key = lowercased with spaces and hyphens removed, so a two-word or hyphenated term
    /// ("Apple Silicon", "luck-filter") matches a token bigram exactly.
    private static func keyed(_ terms: [String]) -> [(key: String, term: String)] {
        terms.map { (key: matchKey($0), term: $0) }
            .filter { !$0.key.isEmpty }
    }

    private static func matchKey(_ text: String) -> String {
        text.lowercased().filter { !$0.isWhitespace && !"-\u{2010}\u{2011}".contains($0) }
    }

    private static func vocabulary() -> VocabularyIndex {
        if let config = state.sessionConfiguration { return config.prepared.vocabulary }
        if let o = state.dictOverride { return VocabularyIndex(o) }
        let u = state.personalizationStore.root.appendingPathComponent(PersonalizationKind.dictionary.filename)
        var t = FileStamp.capture(u)
        if !t.exists, !state.dictSeeded {          // first run: ship a starter vocabulary
            state.dictSeeded = true
            try? state.personalizationStore.ensureTemplate(dictSeed.joined(separator: "\n") + "\n",
                                                             for: .dictionary)
            t = FileStamp.capture(u)
        }
        if let d = state.dictTerms, t == state.dictStamp { return d }
        let rawTerms = t.exists ? ((try? state.personalizationStore.snapshot(.dictionary).entries.map(\.primary)) ?? []) : []
        let d = VocabularyIndex(keyed(rawTerms))
        state.dictTerms = d
        state.dictStamp = t
        log("dictionary loaded: \(d.entries.count) terms")
        return d
    }

    // MARK: - Filler filter

    private static func stripFillers(_ input: OriginText) -> OriginText {
        var value = input.replacingMatches(of: fillers(), withTemplate: "")
        guard value.text.count != input.text.count else { return input }
        value = value.replacingMatches(of: repeatedWhitespace, withTemplate: " ")
        // redteam LOW3: collapse the orphan space left before ANY punctuation (not just , .),
        // then drop a now-meaningless comma sitting right before terminal punctuation.
        value = value.replacingMatches(of: spaceBeforePunctuation, withTemplate: "$1")
        value = value.replacingMatches(of: commaBeforeTerminator, withTemplate: "$1")
        value = trimWhitespace(value)
        if value.text.hasSuffix(",") {
            value = OriginText(text: String(value.text.dropLast()),
                               origins: Array(value.origins.dropLast()))
        }
        // A leading filler ate the sentence's capital; a trailing one ate its period.
        if let f = value.text.first, f.isLowercase,
           let orig = input.text.first(where: \.isLetter), orig.isUppercase {
            // redteam LOW3: don't uppercase a deliberately lowercase-initial word (iPhone,
            // eBay, macOS) — an internal capital means the lowercase start is intentional.
            let firstWord = value.text.prefix { $0.isLetter }
            if !firstWord.dropFirst().contains(where: \.isUppercase) {
                let upper = value.text.prefix(1).uppercased()
                value = OriginText(
                    text: upper + value.text.dropFirst(),
                    origins: Array(repeatElement(value.origins[0], count: upper.count))
                        + value.origins.dropFirst()
                )
            }
        }
        if let last = value.text.last, last.isLetter || last.isNumber,
           let origLast = input.text.trimmingCharacters(in: .whitespaces).last,
           ".!?".contains(origLast) {
            value = OriginText(text: value.text + String(origLast),
                               origins: value.origins + [input.origins.last ?? 0])
        }
        return value
    }

    private static func trimWhitespace(_ input: OriginText) -> OriginText {
        let whitespace = CharacterSet.whitespacesAndNewlines
        func isWhitespace(_ c: Character) -> Bool {
            c.unicodeScalars.allSatisfy(whitespace.contains)
        }

        var start = input.text.startIndex
        while start < input.text.endIndex, isWhitespace(input.text[start]) {
            start = input.text.index(after: start)
        }
        var end = input.text.endIndex
        while end > start {
            let before = input.text.index(before: end)
            guard isWhitespace(input.text[before]) else { break }
            end = before
        }
        let lower = input.text.distance(from: input.text.startIndex, to: start)
        let upper = input.text.distance(from: input.text.startIndex, to: end)
        return OriginText(text: String(input.text[start..<end]),
                          origins: Array(input.origins[lower..<upper]))
    }

    // MARK: - Dictionary correction

    private struct WhitespaceSeparatedToken {
        let slice: Substring
        let text: String
        let gapAfter: Substring
    }

    private static func splitPreservingWhitespace(_ text: String) -> (leading: Substring, tokens: [WhitespaceSeparatedToken]) {
        guard let firstNonWS = text.firstIndex(where: { !$0.isWhitespace }) else {
            return (text[...], [])
        }
        let leading = text[..<firstNonWS]
        var tokens: [WhitespaceSeparatedToken] = []
        var idx = firstNonWS
        while idx < text.endIndex {
            let wordEnd = text[idx...].firstIndex(where: \.isWhitespace) ?? text.endIndex
            let gapEnd = text[wordEnd...].firstIndex(where: { !$0.isWhitespace }) ?? text.endIndex
            let slice = text[idx..<wordEnd]
            tokens.append(WhitespaceSeparatedToken(
                slice: slice,
                text: String(slice),
                gapAfter: text[wordEnd..<gapEnd]
            ))
            idx = gapEnd
        }
        return (leading, tokens)
    }

    /// Exact phrase/case restoration (up to six words), then fuzzy post-correction against
    /// each token and token bigram (so "fluid audio" and "para keet" are repaired, not
    /// just misspellings), including tokens adjacent to `\n` inserted by `spokenPunctuation`.
    /// Surrounding punctuation and exact whitespace/newline separators are preserved.
    ///
    /// A fuzzy match repairs a spelling the recognizer invented ("Kubernets", "para keet").
    /// It never rewrites ordinary words: "the intelligence" stays, even with "Apple
    /// Intelligence" in the dictionary, because real words are what the speaker said.
    private static func correct(_ text: String, changes: inout [Change], origins: [Int],
                                baseOffset: Int = 0) -> String {
        let vocab = vocabulary()
        guard !vocab.entries.isEmpty, !text.isEmpty else { return text }
        // This cache belongs to this cleanup span, so dictionary reloads cannot leave
        // stale hits.
        var lookups: [String: VocabularyIndex.Hit?] = [:]
        func lookup(_ core: String) -> VocabularyIndex.Hit? {
            let key = matchKey(core)
            guard !key.isEmpty else { return nil }
            if let cached = lookups[key] { return cached }
            let hit = vocab.lookup(key)
            lookups[key] = hit
            return hit
        }

        let (leading, toks) = splitPreservingWhitespace(text)
        guard !toks.isEmpty else { return text }

        func startsSentence(_ index: Int) -> Bool {
            guard index > 0 else { return true }
            let previous = toks[index - 1]
            if previous.gapAfter.contains(where: \.isNewline) { return true }
            let closing = previous.text.reversed().prefix { !($0.isLetter || $0.isNumber) }
            return closing.contains { ".!?\u{2026}".contains($0) }
        }
        /// A lowercase term is a spelling, not an instruction to lowercase the word that
        /// opens a sentence ("Yeah, let's go" keeps its capital with "yeah" listed).
        func cased(_ term: String, like original: String, at index: Int) -> String {
            guard let spoken = original.first, spoken.isUppercase,
                  let head = term.first, head.isLowercase,
                  !term.contains(where: \.isUppercase), startsSentence(index) else { return term }
            return head.uppercased() + term.dropFirst()
        }
        /// Real words are left alone unless the recognizer itself wrote one as a name in
        /// the middle of a sentence ("the Claud app" with "Claude" listed).
        func mayRepair(_ spoken: String, to term: String, at index: Int) -> Bool {
            guard OrdinaryWords.contains(spoken) else { return true }
            return spoken.first?.isUppercase == true && term.first?.isUppercase == true
                && !startsSentence(index)
        }
        func single(_ core: String, at index: Int) -> String? {
            let possessive = possessiveSplit(core)
            if let hit = lookup(core),
               hit.exact || (possessive == nil && mayRepair(core, to: hit.term, at: index)) {
                return cased(hit.term, like: core, at: index)
            }
            // "Anthropic's" keeps its ending instead of matching "Anthropic" two edits away.
            if let possessive, let hit = lookup(possessive.stem),
               hit.exact || mayRepair(possessive.stem, to: hit.term, at: index) {
                return cased(hit.term, like: possessive.stem, at: index) + possessive.ending
            }
            return nil
        }
        func joined(_ first: String, _ second: String, at index: Int) -> String? {
            guard let hit = lookup(first + second) else { return nil }
            if !hit.exact {
                guard !(OrdinaryWords.contains(first) && OrdinaryWords.contains(second)),
                      wordsAlign([first, second], with: hit.term) else { return nil }
            }
            return cased(hit.term, like: first, at: index)
        }

        var out = String(leading)
        out.reserveCapacity(text.count)
        var i = 0
        while i < toks.count {
            var phraseHit: (count: Int, term: String, original: String, lead: String, tail: String)?
            for phrase in vocab.phrases where i + phrase.words.count <= toks.count {
                // Never join a multi-word dictionary phrase across a line break (`\n`).
                let crossesNewline = (0..<(phrase.words.count - 1)).contains { offset in
                    toks[i + offset].gapAfter.contains(where: \.isNewline)
                }
                if crossesNewline { continue }

                let parts = (0..<phrase.words.count).map { Self.parts(toks[i + $0].text) }
                guard parts.enumerated().allSatisfy({ offset, part in
                    let edgeOK = (offset == 0 || part.0.isEmpty)
                        && (offset == parts.count - 1 || part.2.isEmpty)
                    return edgeOK && part.1.lowercased() == phrase.words[offset]
                }) else { continue }
                let original = parts.map(\.1).joined(separator: " ")
                phraseHit = (phrase.words.count, cased(phrase.term, like: original, at: i),
                             original, parts.first?.0 ?? "", parts.last?.2 ?? "")
                break
            }
            if let phraseHit {
                if phraseHit.term != phraseHit.original {
                    let position = baseOffset + text.distance(from: text.startIndex,
                                                              to: toks[i].slice.startIndex)
                        + phraseHit.lead.count
                    changes.append(Change(original: phraseHit.original,
                                          replacement: phraseHit.term,
                                          source: .dictionary,
                                          offset: origins[position],
                                          sequence: changes.count))
                }
                out.append(phraseHit.lead + phraseHit.term + phraseHit.tail)
                out.append(contentsOf: toks[i + phraseHit.count - 1].gapAfter)
                i += phraseHit.count
                continue
            }
            let (lead, core, tail) = parts(toks[i].text)
            let hit = core.isEmpty ? nil : single(core, at: i)
            // A bigram is only tried when neither token matches on its own and no newline sits
            // between them — otherwise "to Parakeet" drops "to" or a line break vanishes.
            if hit == nil, tail.isEmpty, i + 1 < toks.count,
               !toks[i].gapAfter.contains(where: \.isNewline) {
                let (leadB, coreB, tailB) = parts(toks[i + 1].text)
                if leadB.isEmpty, !coreB.isEmpty, single(coreB, at: i + 1) == nil,
                   let term = joined(core, coreB, at: i) {
                    let original = core + " " + coreB
                    if term != original {
                        let position = baseOffset + text.distance(from: text.startIndex,
                                                                  to: toks[i].slice.startIndex) + lead.count
                        changes.append(Change(
                            original: original,
                            replacement: term,
                            source: .dictionary,
                            offset: origins[position],
                            sequence: changes.count
                        ))
                    }
                    out.append(lead + term + tailB)
                    out.append(contentsOf: toks[i + 1].gapAfter)
                    i += 2
                    continue
                }
            }
            if let hit, hit != core {
                let position = baseOffset + text.distance(from: text.startIndex,
                                                          to: toks[i].slice.startIndex) + lead.count
                changes.append(Change(
                    original: core,
                    replacement: hit,
                    source: .dictionary,
                    offset: origins[position],
                    sequence: changes.count
                ))
            }
            out.append(hit.map { $0 == core ? toks[i].text : lead + $0 + tail } ?? toks[i].text)
            out.append(contentsOf: toks[i].gapAfter)
            i += 1
        }
        return out
    }

    /// "Claud's" -> ("Claud", "'s"), so the name is matched and the ending kept.
    private static func possessiveSplit(_ core: String) -> (stem: String, ending: String)? {
        for ending in ["'s", "\u{2019}s", "'S", "\u{2019}S"] where core.hasSuffix(ending) {
            let stem = String(core.dropLast(ending.count))
            return stem.isEmpty ? nil : (stem, String(core.suffix(ending.count)))
        }
        return nil
    }

    /// A fuzzy join onto a two-word term must resemble it word for word. Without this the
    /// shared word carries the match and the other word is swallowed whole ("the
    /// intelligence" is four edits from "Apple Intelligence", inside the joined tolerance).
    private static func wordsAlign(_ spoken: [String], with term: String) -> Bool {
        let wanted = term.split(whereSeparator: \.isWhitespace).map { Array(matchKey(String($0))) }
        guard wanted.count == spoken.count else { return true }
        return zip(spoken, wanted).allSatisfy { word, target in
            let characters = Array(matchKey(word))
            return TextSimilarity.boundedEditDistance(
                characters, target, limit: max(characters.count, target.count) / 2
            ) != nil
        }
    }

    /// Splits a token into (leading punctuation, core, trailing punctuation).
    private static func parts(_ t: String) -> (String, String, String) {
        let alnum: (Character) -> Bool = { $0.isLetter || $0.isNumber }
        guard let s = t.firstIndex(where: alnum), let e = t.lastIndex(where: alnum) else {
            return ("", "", "")
        }
        return (String(t[t.startIndex..<s]), String(t[s...e]), String(t[t.index(after: e)...]))
    }

    /// Nearest vocabulary term within 0.25 normalized edit distance, with length-scaled
    /// floors so short vocabulary terms don't rewrite ordinary English.
    /// redteam H3: terms < 6 chars must match exactly (bite→Vite, wisps→Wispr, wisp→Wispr
    /// were all shipped collisions); terms < 8 chars cap the absolute distance at 1; and a
    /// token that is only the term plus an inflection (parakeets→Parakeet) is never rewritten.
    /// Immutable, revision-cached search data. Exact hits, length pruning and bounded
    /// distance preserve the previous match thresholds, inflections and ambiguity rules.
    struct VocabularyIndex {
        struct Entry {
            let key: String
            let term: String
            let characters: [Character]
        }
        let entries: [Entry]
        let phrases: [(words: [String], term: String)]
        private let exact: [String: [Int]]
        private let lengths: [Int: [Int]]

        init(_ vocabulary: [(key: String, term: String)]) {
            let entries = vocabulary.map { Entry(key: $0.key, term: $0.term, characters: Array($0.key)) }
            self.entries = entries
            exact = Dictionary(grouping: entries.indices, by: { entries[$0].key })
            lengths = Dictionary(grouping: entries.indices, by: { entries[$0].characters.count })
            phrases = vocabulary.compactMap { entry in
                let words = entry.term.split(whereSeparator: \.isWhitespace).map { $0.lowercased() }
                return (2...6).contains(words.count) ? (words: words, term: entry.term) : nil
            }.sorted { $0.words.count > $1.words.count }
        }

        /// `exact` is true when the spoken form equals the term apart from case, spaces
        /// and hyphens; false for a near miss inside the edit-distance tolerance.
        struct Hit: Equatable {
            let term: String
            let exact: Bool
        }

        func match(_ core: String) -> String? { lookup(core)?.term }

        func lookup(_ core: String) -> Hit? {
            let k = core.lowercased()
            let characters = Array(k)
            if let hits = exact[k], let first = hits.first {
                let term = entries[first].term
                // The former matcher returned the first exact short term immediately;
                // longer terms refused distinct canonical spellings tied at distance zero.
                return characters.count < 6 || hits.allSatisfy { entries[$0].term == term }
                    ? Hit(term: term, exact: true) : nil
            }
            guard !characters.isEmpty else { return nil }
            var best: (term: String, d: Double)?
            var tied = false
            let minimumLength = max(6, (characters.count * 3 + 3) / 4)
            let maximumLength = characters.count * 4 / 3
            guard minimumLength <= maximumLength else { return nil }
            for length in minimumLength...maximumLength {
                for index in lengths[length] ?? [] {
                    let entry = entries[index]
                    let key = entry.key, term = entry.term
                    if TextSimilarity.isInflection(k, key) { continue }  // parakeets/flowclones etc.
                    let m = max(characters.count, length)
                    let limit = length < 8 ? min(1, m / 4) : m / 4
                    guard let dist = TextSimilarity.boundedEditDistance(characters, entry.characters, limit: limit) else { continue }
                    let d = Double(dist) / Double(m)
                    guard d <= 0.25 else { continue }
                    if best == nil || d < best!.d {
                        best = (term, d)
                        tied = false
                    } else if d == best!.d, term != best!.term {
                        tied = true
                    }
                }
            }
            return tied ? nil : best.map { Hit(term: $0.term, exact: false) }
        }
    }

    /// Two-row Levenshtein, shared with AutoLearn.
    /// ponytail: O(n·m) over ≤20-character tokens — nothing to tune.
    static func distance(_ a: String, _ b: String) -> Int {
        TextSimilarity.editDistance(a, b)
    }

    // MARK: - Snippets (snippets.txt: "trigger -> expansion", one per line)

    private static let triggerMax = 60
    /// First run ships the file EMPTY — there is no sensible default snippet — but with the
    /// syntax in a comment header, so the feature is discoverable without the docs.
    private static let snipHeader = """
        # FlowClone snippets — one per line:  trigger -> expansion
        # Case-insensitive whole-phrase match, mid-sentence included. Use \\n in an
        # expansion for a line break. Supports {{date}}, {{time}}, and {{clipboard}}.
        # Triggers over \(triggerMax) characters are ignored.

        """

    private static let dynamicPlaceholderRegex = try! NSRegularExpression(
        pattern: #"\{\{\s*(date|time|clipboard)\s*\}\}"#,
        options: [.caseInsensitive]
    )

    fileprivate static func renderSnippetBody(_ body: String, environment: SnippetEnvironment) -> String {
        guard body.contains("{{") else { return body }
        let matches = dynamicPlaceholderRegex.matches(in: body, range: NSRange(body.startIndex..., in: body))
        guard !matches.isEmpty else { return body }

        var sampledNow: Date?
        var sampledClipboard: String?
        var out = ""
        var cursor = body.startIndex
        for match in matches {
            guard let fullRange = Range(match.range, in: body),
                  let keyRange = Range(match.range(at: 1), in: body) else { continue }
            out.append(contentsOf: body[cursor..<fullRange.lowerBound])
            switch body[keyRange].lowercased() {
            case "date":
                let date = sampledNow ?? { let d = environment.now(); sampledNow = d; return d }()
                out.append(environment.formattedDate(date))
            case "time":
                let date = sampledNow ?? { let d = environment.now(); sampledNow = d; return d }()
                out.append(environment.formattedTime(date))
            case "clipboard":
                let clip = sampledClipboard ?? { let c = environment.clipboard(); sampledClipboard = c; return c }()
                out.append(clip)
            default:
                out.append(contentsOf: body[fullRange])
            }
            cursor = fullRange.upperBound
        }
        out.append(contentsOf: body[cursor...])
        return out
    }

    fileprivate static func terminalSentenceCharacter(of text: String) -> Character? {
        let trimmed = text.reversed().drop { "\"')]}".contains($0) }
        guard let last = trimmed.first, ".!?".contains(last) else { return nil }
        return last
    }

    /// Prevents `..` / `?.` / `!.` when a snippet expansion already ends with terminal
    /// sentence punctuation and ASR placed a period right after the trigger, while keeping
    /// intentional ellipses (`...`) untouched.
    fileprivate static func trimRedundantPunctuationAfterSnippet(
        _ next: String,
        snippetTerminal: Character?
    ) -> String {
        guard let snippetTerminal, let first = next.first else { return next }
        let rest = next.dropFirst()
        if first == ".", rest.first != "." {
            return String(rest)
        }
        if first == snippetTerminal, rest.first != first {
            return String(rest)
        }
        return next
    }

    private static func buildSnippets(_ pairs: [(String, String)])
        -> (map: [String: String], rx: NSRegularExpression?) {
        var map: [String: String] = [:]
        for (t, e) in pairs {
            // A trigger this long is a mis-split line, not a phrase anyone says out loud —
            // and it would drag a huge alternative through the scan on every utterance.
            guard t.count <= triggerMax else {
                log("snippets: trigger of \(t.count) chars ignored (\(triggerMax) max)")
                continue
            }
            map[t.lowercased()] = e.replacingOccurrences(of: "\\n", with: "\n")
        }
        // Longest alternative first, so a trigger that prefixes another can't win the
        // leftmost match. One alternation = one scan, whatever the snippet count.
        let alts = map.keys.sorted { $0.count == $1.count ? $0 < $1 : $0.count > $1.count }
            .map(NSRegularExpression.escapedPattern(for:)).joined(separator: "|")
        // Lookarounds rather than \b (redteam LOW5): a trigger may end on a non-word char.
        return (map, alts.isEmpty ? nil
                : try? NSRegularExpression(pattern: "(?i)(?<!\\w)(?:\(alts))(?!\\w)"))
    }

    private static func snippetTable() -> (map: [String: String], rx: NSRegularExpression?) {
        if let config = state.sessionConfiguration {
            return config.prepared.snippets
        }
        let u = state.personalizationStore.root.appendingPathComponent(PersonalizationKind.snippet.filename)
        var t = FileStamp.capture(u)
        if !t.exists, !state.snipSeeded {          // first run: an empty file documenting the syntax
            state.snipSeeded = true
            try? state.personalizationStore.ensureTemplate(snipHeader, for: .snippet)
            t = FileStamp.capture(u)
        }
        if let s = state.snipTable, t == state.snipStamp { return s }
        let entries = t.exists ? ((try? state.personalizationStore.snapshot(.snippet).entries) ?? []) : []
        let pairs: [(String, String)] = entries.compactMap { entry in
            guard let replacement = entry.replacement else { return nil }
            return (entry.primary, replacement)
        }
        let s = buildSnippets(pairs)
        state.snipTable = s
        state.snipStamp = t
        if !s.map.isEmpty { log("snippets loaded: \(s.map.count) triggers") }
        return s
    }

    /// F3 / review F-6: match triggers on the PRE-fuzzy text, fuzzy-correct only the
    /// segments between triggers, and defer splicing expansion bodies until `finish()` so
    /// personal snippet contents are never exposed to or edited by model repair review.
    private static func stageSnippets(_ input: OriginText, changes: inout [Change]) -> (
        preSnippetText: String, isBareSnippet: Bool, segments: [StagedCleanup.Segment],
        matchedMap: [String: String], rx: NSRegularExpression?
    ) {
        let text = input.text
        let (map, rx) = snippetTable()
        guard let rx, !text.isEmpty else {
            let corrected = correct(text, changes: &changes, origins: input.origins)
            return (corrected, false, [.text(corrected)], [:], nil)
        }
        // Wispr behavior: the utterance WAS the trigger and the ASR added the terminator.
        var bare = text.trimmingCharacters(in: .whitespacesAndNewlines)
        while let l = bare.last, ".!?".contains(l) { bare = String(bare.dropLast()) }
        if let body = map[bare.lowercased()] {
            return (text, true, [.snippet(trigger: bare, body: body)], [bare.lowercased(): body], rx)
        }
        var preOut = ""
        var segments: [StagedCleanup.Segment] = []
        var matchedMap: [String: String] = [:]
        var cursor = text.startIndex
        for m in rx.matches(in: text, range: NSRange(text.startIndex..., in: text)) {
            guard let r = Range(m.range, in: text), r.lowerBound >= cursor,
                  let body = map[text[r].lowercased()] else { continue }
            let span = correctSpan(String(text[cursor..<r.lowerBound]), changes: &changes,
                                   origins: input.origins,
                                   baseOffset: text.distance(from: text.startIndex, to: cursor))
            let trig = String(text[r])
            segments.append(.text(span))
            segments.append(.snippet(trigger: trig, body: body))
            matchedMap[trig.lowercased()] = body
            preOut += span + trig
            cursor = r.upperBound
        }
        if cursor == text.startIndex {
            let corrected = correct(text, changes: &changes, origins: input.origins)
            return (corrected, false, [.text(corrected)], [:], nil)
        }
        let tail = correctSpan(String(text[cursor...]), changes: &changes,
                               origins: input.origins,
                               baseOffset: text.distance(from: text.startIndex, to: cursor))
        segments.append(.text(tail))
        preOut += tail
        return (preOut, false, segments, matchedMap, rx)
    }

    fileprivate static func expandReviewedSnippets(
        _ text: String,
        map: [String: String],
        rx: NSRegularExpression?,
        codeFormattingEnabled: Bool,
        environment: SnippetEnvironment,
        snippets: inout [String]
    ) -> String {
        guard let rx, !map.isEmpty, !text.isEmpty else {
            return codeFormattingEnabled ? SpokenCodeFormat.apply(text, enabled: true) : text
        }
        var bare = text.trimmingCharacters(in: .whitespacesAndNewlines)
        while let l = bare.last, ".!?".contains(l) { bare = String(bare.dropLast()) }
        if let body = map[bare.lowercased()] {
            snippets.append(bare)
            return renderSnippetBody(body, environment: environment)
        }
        var out = ""
        var cursor = text.startIndex
        var pendingTerminal: Character?
        for m in rx.matches(in: text, range: NSRange(text.startIndex..., in: text)) {
            guard let r = Range(m.range, in: text), r.lowerBound >= cursor,
                  let body = map[text[r].lowercased()] else { continue }
            var leadingSpan = String(text[cursor..<r.lowerBound])
            if let pendingTerminal {
                leadingSpan = trimRedundantPunctuationAfterSnippet(leadingSpan, snippetTerminal: pendingTerminal)
            }
            if codeFormattingEnabled, !leadingSpan.isEmpty {
                leadingSpan = SpokenCodeFormat.apply(leadingSpan, enabled: true)
            }
            snippets.append(String(text[r]))
            let rendered = renderSnippetBody(body, environment: environment)
            out += leadingSpan + rendered
            pendingTerminal = terminalSentenceCharacter(of: rendered)
            cursor = r.upperBound
        }
        if cursor == text.startIndex {
            return codeFormattingEnabled ? SpokenCodeFormat.apply(text, enabled: true) : text
        }
        var tail = String(text[cursor...])
        if let pendingTerminal {
            tail = trimRedundantPunctuationAfterSnippet(tail, snippetTerminal: pendingTerminal)
        }
        if codeFormattingEnabled, !tail.isEmpty {
            tail = SpokenCodeFormat.apply(tail, enabled: true)
        }
        return out + tail
    }

    /// Preserves leading/trailing whitespace edges around a span between snippet triggers.
    private static func correctSpan(_ s: String, changes: inout [Change], origins: [Int],
                                    baseOffset: Int) -> String {
        guard let a = s.firstIndex(where: { !$0.isWhitespace }),
              let b = s.lastIndex(where: { !$0.isWhitespace }) else { return s }
        return String(s[..<a])
            + correct(String(s[a...b]), changes: &changes, origins: origins,
                      baseOffset: baseOffset + s.distance(from: s.startIndex, to: a))
            + String(s[s.index(after: b)...])
    }
