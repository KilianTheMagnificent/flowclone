// Deterministic cleanup — PLAN.md Phase 3 "Clean": filler filter + fuzzy dictionary
// correction + snippet expansion, zero added latency (one stat() call per config file
// per utterance).
// Prompt mode's rewrite (Prompter.swift) runs on top of this and falls back to it.
// The compiled configuration cache is shared by the release path and the live preview.
// Keep it behind one recursive lock so overlapping cleanup cannot race a reload or test seam.
import Cocoa
import Foundation

/// Text plus one raw-transcript character anchor per grapheme. Deterministic cleanup only
/// deletes or replaces spans; carrying the anchors through those actual edits keeps later
/// correction notices in true encounter order even when identical words are removed.
struct OriginText {
    let text: String
    let origins: [Int]

    init(_ text: String) {
        self.text = text
        origins = Array(0..<text.count)
    }

    init(text: String, origins: [Int]) {
        assert(text.count == origins.count)
        self.text = text
        self.origins = origins
    }

    /// Foundation-compatible regex replacement with provenance. Every inserted character
    /// inherits the first raw anchor of its match; byte-identical matches retain all anchors.
    func replacingMatches(of rx: NSRegularExpression, withTemplate template: String) -> OriginText {
        let matches = rx.matches(in: text, range: NSRange(text.startIndex..., in: text))
        guard !matches.isEmpty else { return self }

        var output = ""
        output.reserveCapacity(text.count)
        var outputOrigins: [Int] = []
        outputOrigins.reserveCapacity(origins.count)
        var cursor = text.startIndex
        var originCursor = 0

        for match in matches {
            guard let range = Range(match.range, in: text) else { continue }
            let lower = originCursor + text.distance(from: cursor, to: range.lowerBound)
            let upper = lower + text.distance(from: range.lowerBound, to: range.upperBound)
            output.append(contentsOf: text[cursor..<range.lowerBound])
            outputOrigins.append(contentsOf: origins[originCursor..<lower])

            let original = String(text[range])
            let replacement = rx.replacementString(for: match, in: text, offset: 0,
                                                   template: template)
            output.append(contentsOf: replacement)
            if replacement == original, replacement.count == upper - lower {
                outputOrigins.append(contentsOf: origins[lower..<upper])
            } else if !replacement.isEmpty {
                let anchor = origins[lower]
                outputOrigins.append(contentsOf: repeatElement(anchor, count: replacement.count))
            }
            cursor = range.upperBound
            originCursor = upper
        }
        output.append(contentsOf: text[cursor...])
        outputOrigins.append(contentsOf: origins[originCursor...])
        return OriginText(text: output, origins: outputOrigins)
    }
}

enum Cleaner {
    enum ChangeSource: Equatable, Sendable {
        case learnedCorrection
        case dictionary
    }

    /// Injectable date, time, and clipboard provider for dynamic snippet placeholders
    /// (`{{date}}`, `{{time}}`, `{{clipboard}}`).
    struct SnippetEnvironment: Sendable {
        var now: @Sendable () -> Date
        var timeZone: TimeZone
        var clipboard: @Sendable () -> String

        init(
            now: @escaping @Sendable () -> Date = { Date() },
            timeZone: TimeZone = .current,
            clipboard: @escaping @Sendable () -> String = SnippetEnvironment.liveClipboard
        ) {
            self.now = now
            self.timeZone = timeZone
            self.clipboard = clipboard
        }

        static let live = SnippetEnvironment()

        private static let concealedTypes: [NSPasteboard.PasteboardType] = [
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
            NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        ]

        static func liveClipboard() -> String {
            let readPasteboard: @Sendable () -> String = {
                let pb = NSPasteboard.general
                if let types = pb.types, types.contains(where: { concealedTypes.contains($0) }) {
                    return ""
                }
                guard let raw = pb.string(forType: .string) else { return "" }
                let clipped = raw.count > 4_000 ? String(raw.prefix(4_000)) : raw
                var normalized = ""
                normalized.reserveCapacity(clipped.utf8.count)
                for c in clipped {
                    normalized.append(c.isNewline ? "\n" : c)
                }
                return normalized
            }
            if Thread.isMainThread {
                return readPasteboard()
            }
            return DispatchQueue.main.sync(execute: readPasteboard)
        }

        func formattedDate(_ date: Date) -> String {
            let formatter = DateFormatter()
            formatter.locale = Locale(identifier: "en_US_POSIX")
            formatter.calendar = Calendar(identifier: .gregorian)
            formatter.timeZone = timeZone
            formatter.dateFormat = "yyyy-MM-dd"
            return formatter.string(from: date)
        }

        func formattedTime(_ date: Date) -> String {
            let formatter = DateFormatter()
            formatter.locale = Locale(identifier: "en_US_POSIX")
            formatter.calendar = Calendar(identifier: .gregorian)
            formatter.timeZone = timeZone
            formatter.dateFormat = "HH:mm"
            return formatter.string(from: date)
        }
    }

    /// One deterministic word substitution, captured where it happens rather than
    /// reconstructed from raw/final text (which would also include fillers, punctuation,
    /// snippets and later formatting). `offset`/`sequence` keep the user-facing summary in
    /// encounter order even though learned rules are evaluated in config-file order.
    struct Change: Equatable, Sendable {
        let original: String
        let replacement: String
        let source: ChangeSource
        fileprivate var offset: Int
        fileprivate let sequence: Int

        static func == (lhs: Change, rhs: Change) -> Bool {
            lhs.original == rhs.original
                && lhs.replacement == rhs.replacement
                && lhs.source == rhs.source
        }
    }

    struct Result: Sendable {
        let text: String
        let changes: [Change]
        var expandedSnippets: [String] = []
        /// Names of the spoken self-repair rules that fired (never the words).
        var repairs: [String] = []
    }

    /// Cleanup up to (but excluding) snippet body expansion and slash-command formatting.
    /// Snippet triggers are matched and shielded from fuzzy dictionary edits now, while their
    /// replacement bodies are spliced in only when `finish` runs after any model repair review.
    struct StagedCleanup: @unchecked Sendable {
        fileprivate enum Segment {
            case text(String)
            case snippet(trigger: String, body: String)
        }
        let preSnippetText: String
        let changes: [Change]
        let repairs: [String]
        let isBareSnippet: Bool
        fileprivate let segments: [Segment]
        fileprivate let matchedMap: [String: String]
        fileprivate let rx: NSRegularExpression?
        fileprivate let appProfile: ResolvedAppProfile
        fileprivate let snippetEnvironment: SnippetEnvironment

        var hasSnippets: Bool { !matchedMap.isEmpty }

        var snippetTriggers: [String] {
            segments.compactMap {
                if case .snippet(let trigger, _) = $0 { return trigger }
                return nil
            }
        }

        /// Text ready for Smart Cleanup / repair review: applies `SpokenCodeFormat` and
        /// `SlashCommands` safely to non-snippet text spans while keeping snippet triggers
        /// unexpanded so private snippet bodies never leave the Mac.
        var preReviewText: String {
            guard !hasSnippets else {
                // With snippets present, keep triggers untouched and only apply leading slash command
                // on segment 0 so a post-snippet span isn't mistaken for line-start.
                var out = ""
                for (index, segment) in segments.enumerated() {
                    switch segment {
                    case .text(let s):
                        var span = s
                        if index == 0, !span.isEmpty {
                            span = SlashCommands.apply(span, profile: appProfile)
                        }
                        out += span
                    case .snippet(let trigger, _):
                        out += trigger
                    }
                }
                return out
            }
            var out = preSnippetText
            if appProfile.codeFormattingEnabled, !out.isEmpty {
                out = SpokenCodeFormat.apply(out, enabled: true)
            }
            if !out.isEmpty {
                out = SlashCommands.apply(out, profile: appProfile)
            }
            return out
        }

        func finish(_ reviewedText: String? = nil) -> Result {
            let expandedText: String
            var expanded: [String] = []
            let formatCode = appProfile.codeFormattingEnabled

            if let reviewedText, reviewedText != preSnippetText {
                expandedText = Cleaner.expandReviewedSnippets(
                    reviewedText,
                    map: matchedMap,
                    rx: rx,
                    codeFormattingEnabled: formatCode,
                    environment: snippetEnvironment,
                    snippets: &expanded
                )
            } else {
                var out = ""
                var idx = 0
                var pendingDropLeadingPunct = false
                var previousSnippetTerminal: Character?
                while idx < segments.count {
                    switch segments[idx] {
                    case .text(let s):
                        var span = s
                        if pendingDropLeadingPunct {
                            span = Cleaner.trimRedundantPunctuationAfterSnippet(
                                span,
                                snippetTerminal: previousSnippetTerminal
                            )
                            pendingDropLeadingPunct = false
                            previousSnippetTerminal = nil
                        }
                        if formatCode, !span.isEmpty {
                            span = SpokenCodeFormat.apply(span, enabled: true)
                        }
                        out += span
                    case .snippet(let trigger, let body):
                        expanded.append(trigger)
                        let rendered = Cleaner.renderSnippetBody(body, environment: snippetEnvironment)
                        out += rendered
                        if let terminal = Cleaner.terminalSentenceCharacter(of: rendered) {
                            pendingDropLeadingPunct = true
                            previousSnippetTerminal = terminal
                        } else {
                            pendingDropLeadingPunct = false
                            previousSnippetTerminal = nil
                        }
                    }
                    idx += 1
                }
                expandedText = out
            }
            let output = SlashCommands.apply(expandedText, profile: appProfile)
            return Result(text: output, changes: changes, expandedSnippets: expanded, repairs: repairs)
        }
    }

    /// Compiled once on the vocabulary-capture worker, then reused by live previews and
    /// final delivery. Session rules retain the indexed matcher used by global cleanup.
    struct PreparedConfiguration: @unchecked Sendable {
        let corrections: [(rx: NSRegularExpression, right: String)]
        let vocabulary: VocabularyIndex
        let phoneticIndex: PhoneticMatcher.Index
        let snippets: (map: [String: String], rx: NSRegularExpression?)

        init(_ entries: [PersonalizationDraft]) {
            let dictionaryTerms = entries.filter { $0.kind == .dictionary }.map(\.primary)
            corrections = compile(entries.filter { $0.kind == .correction }.compactMap { entry in
                entry.replacement.map { (entry.primary, $0) }
            })
            vocabulary = VocabularyIndex(keyed(dictionaryTerms))
            phoneticIndex = PhoneticMatcher.Index(vocabulary: dictionaryTerms)
            snippets = buildSnippets(entries.filter { $0.kind == .snippet }.compactMap { entry in
                entry.replacement.map { (entry.primary, $0) }
            })
        }

        /// Returns an mtime-cached `PreparedConfiguration` for a store root without
        /// re-reading files, SHA-256 hashing, or recompiling regexes when stamps match.
        static func prepare(for store: PersonalizationStore = .shared) -> PreparedConfiguration {
            Cleaner.preparedForStore(store)
        }
    }

    /// Backwards-compatible namespace alias for mtime-cached base configuration preparation.
    enum Configuration {
        static func prepare(
            store: PersonalizationStore = .shared,
            targetApp: String? = nil,
            contextWords: [String] = []
        ) -> PersonalizationConfiguration {
            _ = contextWords // Per-utterance context words stay ephemeral in ContextVocabulary.
            let sets: VocabularySets = state.withLock {
                if store.root == PersonalizationStore.shared.root {
                    return VocabularySets.shared
                }
                let path = store.root.standardizedFileURL.path
                if let cached = state.setsByRoot[path] {
                    return cached
                }
                let created = VocabularySets(root: store.root)
                if state.setsByRoot.count >= 16 {
                    state.setsByRoot.removeAll(keepingCapacity: true)
                }
                state.setsByRoot[path] = created
                return created
            }
            return sets.configuration(bundleID: targetApp)
        }
    }

    /// One canonical reader/writer owns dictionary, snippet and correction syntax. Cleaner
    /// keeps only compiled, mtime-keyed views of its immutable snapshots. State lives in a
    /// locked reference rather than mutable static variables: preview and final cleanup
    /// can overlap, and the test store swap must be atomic with every cache access.
    private final class ConfigurationState: @unchecked Sendable {
        struct StoreCacheKey: Hashable {
            let rootPath: String
            let dictionary: FileStamp
            let snippet: FileStamp
            let correction: FileStamp
        }

        let lock = NSRecursiveLock()
        var personalizationStore = PersonalizationStore.shared
        var snippetEnvironment = SnippetEnvironment.live
        var corrPairs: [(rx: NSRegularExpression, right: String)]?
        var corrStamp: FileStamp?
        var corrOverride: [(String, String)]?
        var fillerRegex: NSRegularExpression?
        var fillerStamp: FileStamp?
        var dictTerms: VocabularyIndex?
        var dictStamp: FileStamp?
        var dictSeeded = false
        var dictOverride: [(key: String, term: String)]?
        var snipTable: (map: [String: String], rx: NSRegularExpression?)?
        var snipStamp: FileStamp?
        var snipSeeded = false
        var sessionConfiguration: PersonalizationConfiguration?
        var storePreparedCache: [StoreCacheKey: PreparedConfiguration] = [:]
        var setsByRoot: [String: VocabularySets] = [:]

        func withLock<T>(_ body: () throws -> T) rethrows -> T {
            lock.lock()
            defer { lock.unlock() }
            return try body()
        }
    }

    private static let state = ConfigurationState()
    static var supportDir: URL { state.withLock { state.personalizationStore.root } }

    /// fillers.txt / dictionary.txt extend these; both reload when their mtime changes.
    private static let fillerDefaults = ["um", "uh", "erm", "uhm"]
    private static let dictSeed = ["FlowClone", "FluidAudio", "Parakeet", "Wispr"]

    private static func preparedForStore(_ store: PersonalizationStore) -> PreparedConfiguration {
        state.withLock {
            let rootURL = store.root.standardizedFileURL
            let dictStamp = FileStamp.capture(rootURL.appendingPathComponent(PersonalizationKind.dictionary.filename))
            let snipStamp = FileStamp.capture(rootURL.appendingPathComponent(PersonalizationKind.snippet.filename))
            let corrStamp = FileStamp.capture(rootURL.appendingPathComponent(PersonalizationKind.correction.filename))
            let key = ConfigurationState.StoreCacheKey(
                rootPath: rootURL.path,
                dictionary: dictStamp,
                snippet: snipStamp,
                correction: corrStamp
            )
            if let cached = state.storePreparedCache[key] {
                return cached
            }
            var drafts: [PersonalizationDraft] = []
            if dictStamp.exists {
                drafts += ((try? store.snapshot(.dictionary).entries) ?? []).map(\.draft)
            }
            if snipStamp.exists {
                drafts += ((try? store.snapshot(.snippet).entries) ?? []).map(\.draft)
            }
            if corrStamp.exists {
                drafts += ((try? store.snapshot(.correction).entries) ?? []).map(\.draft)
            }
            let prepared = PreparedConfiguration(drafts)
            if state.storePreparedCache.count >= 16 {
                state.storePreparedCache.removeAll(keepingCapacity: true)
            }
            state.storePreparedCache[key] = prepared
            return prepared
        }
    }

    static func clean(_ text: String) -> String {
        cleanWithChanges(text).text
    }

    static func clean(_ text: String, bundleID: String?) -> String {
        let result = cleanWithChanges(text, bundleID: bundleID).text
        guard let bundleID else { return result }
        let profile = state.withLock {
            AppProfiles(root: state.personalizationStore.root).resolve(bundleID: bundleID)
        }
        return profile.formatOutput(result, raw: text)
    }

    /// String output plus the exact dictionary-backed substitutions that produced it.
    /// The array remains per-call state so overlapping cleanup passes can never
    /// attribute one utterance's changes to another.
    static func cleanWithChanges(
        _ text: String,
        configuration: PersonalizationConfiguration? = nil,
        bundleID: String? = nil
    ) -> Result {
        stage(text, configuration: configuration, bundleID: bundleID).finish()
    }

    /// Runs corrections, filler stripping, spoken repairs, spoken punctuation, and fuzzy
    /// dictionary matching on non-snippet spans while keeping snippet triggers unexpanded.
    static func stage(
        _ text: String,
        configuration: PersonalizationConfiguration? = nil,
        bundleID: String? = nil
    ) -> StagedCleanup {
        state.withLock {
            let previous = state.sessionConfiguration
            state.sessionConfiguration = configuration
            defer { state.sessionConfiguration = previous }

            let effectiveProfile: ResolvedAppProfile
            if let configuration {
                if let bundleID, configuration.bundleID == nil {
                    effectiveProfile = AppProfiles(root: state.personalizationStore.root).resolve(bundleID: bundleID)
                } else {
                    effectiveProfile = configuration.appProfile
                }
            } else if let bundleID {
                effectiveProfile = AppProfiles(root: state.personalizationStore.root).resolve(bundleID: bundleID)
            } else {
                effectiveProfile = .unnamedDefault
            }

            var changes: [Change] = []
            let learned = applyCorrections(text, changes: &changes)
            let repaired = SmartFormat.spokenRepairs(stripFillers(learned))
            let prepared = SmartFormat.spokenPunctuation(repaired.text)
            let staged = stageSnippets(prepared, changes: &changes)
            changes.sort {
                $0.offset == $1.offset ? $0.sequence < $1.sequence : $0.offset < $1.offset
            }
            return StagedCleanup(
                preSnippetText: staged.preSnippetText,
                changes: changes,
                repairs: repaired.rules.map(\.rawValue),
                isBareSnippet: staged.isBareSnippet,
                segments: staged.segments,
                matchedMap: staged.matchedMap,
                rx: staged.rx,
                appProfile: effectiveProfile,
                snippetEnvironment: state.snippetEnvironment
            )
        }
    }

    /// Test seam for deterministic `{{date}}`, `{{time}}`, and `{{clipboard}}` expansions.
    @discardableResult
    static func withSnippetEnvironment<T>(_ environment: SnippetEnvironment,
                                          _ body: () throws -> T) rethrows -> T {
        try state.withLock {
            let previous = state.snippetEnvironment
            state.snippetEnvironment = environment
            defer { state.snippetEnvironment = previous }
            return try body()
        }
    }

    // MARK: - Learned corrections (corrections.txt: "wrong -> right", one per line)

    private static func compile(_ pairs: [(String, String)]) -> [(rx: NSRegularExpression, right: String)] {
        func isWord(_ c: Character?) -> Bool { c.map { $0.isLetter || $0.isNumber || $0 == "_" } ?? false }
        return pairs.compactMap { w, r in
            // redteam LOW5: a \b next to a non-word char (C#, .NET) can never be satisfied,
            // so the pattern silently matches nothing. Use \b only where the term's edge is a
            // word char; a non-word lookaround otherwise.
            let left = isWord(w.first) ? "\\b" : "(?<![\\w])"
            let right = isWord(w.last) ? "\\b" : "(?![\\w])"
            return (try? NSRegularExpression(pattern: "(?i)\(left)\(NSRegularExpression.escapedPattern(for: w))\(right)"))
                .map { (rx: $0, right: r) }
        }
    }

    private static func corrections() -> [(rx: NSRegularExpression, right: String)] {
        if let config = state.sessionConfiguration {
            return config.prepared.corrections
        }
        if let o = state.corrOverride { return compile(o) }
        let u = state.personalizationStore.root.appendingPathComponent(PersonalizationKind.correction.filename)
        let t = FileStamp.capture(u)
        if let c = state.corrPairs, t == state.corrStamp { return c }
        let entries = t.exists ? ((try? state.personalizationStore.snapshot(.correction).entries) ?? []) : []
        let pairs: [(String, String)] = entries.compactMap { entry in
            guard let replacement = entry.replacement else { return nil }
            return (entry.primary, replacement)
        }
        let c = compile(pairs)
        state.corrPairs = c
        state.corrStamp = t
        if !c.isEmpty { log("corrections loaded: \(c.count) pairs") }
        return c
    }

    /// Exact learned fixes run FIRST, on the raw ASR text, before fillers and fuzzy.
    private static func applyCorrections(_ text: String, changes: inout [Change]) -> OriginText {
        let source = OriginText(text)
        struct Hit {
            let range: Range<String.Index>
            let nsRange: NSRange
            let right: String
            let rule: Int
        }
        var hits: [Hit] = []
        for (rule, pair) in corrections().enumerated() {
            for match in pair.rx.matches(in: text, range: NSRange(text.startIndex..., in: text)) {
                if let range = Range(match.range, in: text) {
                    hits.append(Hit(range: range, nsRange: match.range,
                                    right: pair.right, rule: rule))
                }
            }
        }
        // All rules match the original transcript exactly once. A replacement can never
        // feed a later rule and silently cascade (alpha→beta→Gamma). For overlapping manual
        // rules, earliest then longest wins; file order breaks a true tie.
        hits.sort {
            if $0.nsRange.location != $1.nsRange.location {
                return $0.nsRange.location < $1.nsRange.location
            }
            if $0.nsRange.length != $1.nsRange.length { return $0.nsRange.length > $1.nsRange.length }
            return $0.rule < $1.rule
        }
        var chosen: [Hit] = []
        var end = -1
        for hit in hits where hit.nsRange.location >= end {
            chosen.append(hit)
            end = NSMaxRange(hit.nsRange)
        }
        guard !chosen.isEmpty else { return source }

        var output = ""
        output.reserveCapacity(text.count)
        var outputOrigins: [Int] = []
        outputOrigins.reserveCapacity(source.origins.count)
        var cursor = text.startIndex
        var originCursor = 0
        for hit in chosen {
            let lower = originCursor + text.distance(from: cursor, to: hit.range.lowerBound)
            let upper = lower + text.distance(from: hit.range.lowerBound, to: hit.range.upperBound)
            output.append(contentsOf: text[cursor..<hit.range.lowerBound])
            outputOrigins.append(contentsOf: source.origins[originCursor..<lower])
            let original = String(text[hit.range])
            let anchor = source.origins[lower]
            if original != hit.right {
                changes.append(Change(original: original, replacement: hit.right,
                                      source: .learnedCorrection, offset: anchor,
                                      sequence: changes.count))
            }
            output.append(contentsOf: hit.right)
            if original == hit.right, hit.right.count == upper - lower {
                outputOrigins.append(contentsOf: source.origins[lower..<upper])
            } else {
                outputOrigins.append(contentsOf: repeatElement(anchor, count: hit.right.count))
            }
            cursor = hit.range.upperBound
            originCursor = upper
        }
        output.append(contentsOf: text[cursor...])
        outputOrigins.append(contentsOf: source.origins[originCursor...])
        return OriginText(text: output, origins: outputOrigins)
    }

    /// Is `wrong` already the left side of a learned pair? The compiled patterns are
    /// `(?i)\bwrong\b`, so matching a single word token against them is an exact,
    /// case-insensitive hit. Used by AutoLearn to skip what it already taught us.
    static func correctionKnown(wrong: String) -> Bool {
        state.withLock {
            let r = NSRange(wrong.startIndex..., in: wrong)
            return corrections().contains { $0.rx.firstMatch(in: wrong, range: r) != nil }
        }
    }

    /// Voice command: "correct (the) spelling (of) <wrong> to <right>".
    /// ponytail: splits on the LAST " to " — a <wrong> that itself contains " to "
    /// needs a manual corrections.txt line instead.
    static func parseCorrectionCommand(_ text: String) -> (wrong: String, right: String)? {
        var t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        while let l = t.last, ".!?,".contains(l) { t = String(t.dropLast()) }
        let lower = t.lowercased()
        var rest: Substring?
        for p in ["correct the spelling of ", "correct spelling of ", "correct spelling "]
        where lower.hasPrefix(p) {
            rest = t.dropFirst(p.count)
            break
        }
        guard let rest,
              let sep = rest.range(of: " to ", options: [.backwards, .caseInsensitive]) else { return nil }
        let w = rest[..<sep.lowerBound].trimmingCharacters(in: .whitespaces)
        let r = rest[sep.upperBound...].trimmingCharacters(in: .whitespaces)
        // Output casing is semantic (iphone→iPhone), so only a canonically identical pair
        // is a no-op. The store applies the heard/left side case-insensitively afterward.
        guard !w.isEmpty, !r.isEmpty,
              w.precomposedStringWithCanonicalMapping
                != r.precomposedStringWithCanonicalMapping else { return nil }
        // redteam H2: constrain SHAPE, not vocabulary. A real spelling fix is a short
        // token/bigram with no stop words on either side; ordinary sentences ("…the third
        // paragraph to match the style guide") fail this and fall through to a normal paste.
        // A swallowed dictation is unrecoverable; a stray paste is not.
        let stops: Set<String> = ["the","of","and","a","an","to","in","is","it","for","on","or","with","that","this"]
        func shapeOK(_ s: String) -> Bool {
            guard s.count <= 25 else { return false }
            let toks = s.lowercased().split(whereSeparator: \.isWhitespace).map(String.init)
            return toks.count <= 2 && !toks.contains(where: stops.contains)
        }
        guard shapeOK(w), shapeOK(r) else { return nil }
        // Shape alone still accepts "Correct spelling before sending to Marcus." — two short
        // stop-word-free sides that share nothing. A spelling correction changes SPELLING, so
        // the two sides must still be near neighbours; half the longer side is generous enough
        // for "stripe → Stripe Inc" and far too tight for an ordinary sentence.
        let lw = w.lowercased().filter { !$0.isWhitespace }
        let lr = r.lowercased().filter { !$0.isWhitespace }
        guard TextSimilarity.editDistance(lw, lr)
                <= max(2, (max(lw.count, lr.count) + 1) / 2) else { return nil }
        return (w, r)
    }

